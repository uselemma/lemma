// Writes src/version.ts from package.json so the User-Agent always names the
// version being built. The file is not committed: pnpm install (prepare),
// build, type-check, and test regenerate it, including for the plugins that
// bundle this package's source.
import { readFile, writeFile } from "node:fs/promises";

const packageUrl = new URL("../package.json", import.meta.url);
const { name, version } = JSON.parse(await readFile(packageUrl, "utf8"));

await writeFile(
  new URL("../src/version.ts", import.meta.url),
  `// Generated by scripts/write-version.mjs from package.json. Do not edit.\n` +
    `export const SDK_PACKAGE_NAME = ${JSON.stringify(name)};\n` +
    `export const SDK_VERSION = ${JSON.stringify(version)};\n`,
);
